    paths = np.empty((n_runs, days + 1))
    paths[:, 0] = baseline
    for d in range(1, days + 1):
        daily_returns = rng.normal(0, daily_volatility, size=n_runs)
        paths[:, d] = paths[:, d - 1] * (1 + daily_returns)
    return paths


