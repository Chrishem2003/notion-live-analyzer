"""Application-level encryption for persisted workflow payloads.

The workflow UI requires a Fernet key before initializing the runtime. Legacy
plaintext rows remain readable and are migrated in place when a key is configured.
SQLite metadata (IDs, task types, statuses, timestamps, hashes, and event history)
is not encrypted by this module.
"""
from __future__ import annotations

import json
import os
from typing import Any, Mapping

from cryptography.fernet import Fernet, InvalidToken

ENCRYPTED_PREFIX = "enc:v1:"


class WorkflowStorageConfigurationError(RuntimeError):
    """Raised when workflow payload encryption is not safely configured."""


class WorkflowStorageError(RuntimeError):
    """Raised when encrypted workflow data cannot be decrypted or decoded."""


def validate_storage_key(value: str | bytes) -> bytes:
    """Validate a Fernet key and return its byte representation."""
    key = value.encode("ascii") if isinstance(value, str) else value
    if not isinstance(key, bytes):
        raise WorkflowStorageConfigurationError("Workflow encryption key must be a Fernet key string.")
    try:
        Fernet(key)
    except (TypeError, ValueError) as exc:
        raise WorkflowStorageConfigurationError(
            "WORKFLOW_RUNTIME_ENCRYPTION_KEY must be a valid Fernet key generated by Fernet.generate_key()."
        ) from exc
    return key


def load_workflow_storage_key(
    secrets: Mapping[str, Any] | None = None,
    environ: Mapping[str, str] | None = None,
) -> bytes:
    """Load and validate the required key; explicit empty mappings stay isolated."""
    secret_store = secrets if secrets is not None else {}
    environment = os.environ if environ is None else environ
    value = secret_store.get("WORKFLOW_RUNTIME_ENCRYPTION_KEY")
    if not isinstance(value, str) or not value.strip():
        value = environment.get("WORKFLOW_RUNTIME_ENCRYPTION_KEY")
    if not isinstance(value, str) or not value.strip():
        raise WorkflowStorageConfigurationError(
            "WORKFLOW_RUNTIME_ENCRYPTION_KEY is required; workflow execution is locked without it."
        )
    return validate_storage_key(value)


def encrypt_storage_text(value: str, key: bytes | None) -> str:
    """Encrypt text when a key is configured; retain plaintext only for isolated tests/legacy use."""
    if not isinstance(value, str):
        raise TypeError("Stored workflow text must be a string.")
    if key is None:
        return value
    return ENCRYPTED_PREFIX + Fernet(validate_storage_key(key)).encrypt(value.encode("utf-8")).decode("ascii")


def decrypt_storage_text(value: str, key: bytes | None) -> str:
    """Decrypt versioned ciphertext; plaintext legacy rows remain readable."""
    if not isinstance(value, str):
        raise WorkflowStorageError("Stored workflow value has an invalid type.")
    if not value.startswith(ENCRYPTED_PREFIX):
        return value
    if key is None:
        raise WorkflowStorageConfigurationError(
            "This workflow database contains encrypted records; configure WORKFLOW_RUNTIME_ENCRYPTION_KEY."
        )
    token = value[len(ENCRYPTED_PREFIX):]
    try:
        return Fernet(validate_storage_key(key)).decrypt(token.encode("ascii")).decode("utf-8")
    except (InvalidToken, UnicodeError, ValueError) as exc:
        raise WorkflowStorageError(
            "Workflow payload decryption failed; verify the configured key and restore procedure."
        ) from exc


def encode_storage_json(value: Any, key: bytes | None) -> str:
    """Serialize finite JSON and encrypt the serialized text when configured."""
    try:
        encoded = json.dumps(
            value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False
        )
    except (TypeError, ValueError) as exc:
        raise ValueError("workflow storage value must be finite JSON-compatible data") from exc
    return encrypt_storage_text(encoded, key)


def decode_storage_json(value: str, key: bytes | None) -> Any:
    """Read encrypted or legacy plaintext JSON."""
    decoded = decrypt_storage_text(value, key)
    try:
        return json.loads(decoded)
    except (TypeError, ValueError) as exc:
        raise WorkflowStorageError("Stored workflow JSON is invalid.") from exc
