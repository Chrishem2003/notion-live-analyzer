    secret = os.environ.get("STRIPE_WEBHOOK_SECRET")
    if not secret:
        raise RuntimeError("STRIPE_WEBHOOK_SECRET not set")
    client = _client()
    return client.Webhook.construct_event(payload, sig_header, secret)

